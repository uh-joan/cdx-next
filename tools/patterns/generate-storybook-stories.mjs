#!/usr/bin/env node
/**
 * Generate Storybook `Patterns/*` stories from the pattern examples.
 *
 * Each pattern's live example already lives once in docs-website as an
 * `*.example.ts` exporting an `InputViewerComponent` whose `dynamicComponent`
 * is a self-contained standalone component. This script emits one Storybook
 * story file per example that renders that same component — so the stories are
 * generated from the single source, never hand-maintained.
 *
 * Title layout:
 *   - pattern with one example   → `Patterns/<Pattern Title>`
 *   - pattern with many examples → `Patterns/<Pattern Title>/<Example Name>`
 *
 * (Angular Storybook pins the component at the meta level, so each example gets
 * its own file rather than several stories sharing one meta.)
 *
 * Usage:
 *   node tools/patterns/generate-storybook-stories.mjs          # write
 *   node tools/patterns/generate-storybook-stories.mjs --check  # verify, exit 1 on drift
 */
import {
  readFileSync,
  writeFileSync,
  readdirSync,
  existsSync,
  mkdirSync,
  rmSync,
} from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import prettier from 'prettier';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..', '..');
const patternsDir = join(
  repoRoot,
  'packages/docs-website/src/app/pages/patterns',
);
const storiesDir = join(
  repoRoot,
  'packages/storybook/src/stories/patterns',
);

const isCheck = process.argv.includes('--check');
const errors = [];

function readFrontmatter(file) {
  const text = readFileSync(file, 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return null;
  return yaml.load(m[1]);
}

function parseExample(file) {
  const text = readFileSync(file, 'utf8');
  const constName = text.match(
    /export const (\w+): InputViewerComponent/,
  )?.[1];
  const exampleName = text.match(/exampleName:\s*'([^']*)'/)?.[1];
  return constName && exampleName ? { constName, exampleName } : null;
}

// Collect the ordered example files for a pattern from its examples/index.ts.
function exampleFiles(patternDir) {
  const indexFile = join(patternDir, 'examples', 'index.ts');
  if (!existsSync(indexFile)) return [];
  const stems = [...readFileSync(indexFile, 'utf8').matchAll(
    /export \* from '\.\/([^']+)'/g,
  )].map((m) => m[1]);
  return stems
    .map((stem) => {
      const file = join(patternDir, 'examples', `${stem}.ts`);
      if (!existsSync(file)) {
        errors.push(`missing example file ${stem}.ts in ${patternDir}`);
        return null;
      }
      const parsed = parseExample(file);
      if (!parsed) {
        errors.push(`could not parse export/exampleName in ${stem}.ts`);
        return null;
      }
      return { stem, ...parsed };
    })
    .filter(Boolean);
}

const generated = {};

for (const id of readdirSync(patternsDir)) {
  const patternDir = join(patternsDir, id);
  const guide = join(patternDir, `${id}.guide.md`);
  if (!existsSync(guide)) continue;
  const fm = readFrontmatter(guide);
  if (!fm?.title) {
    errors.push(`no title in ${id}.guide.md`);
    continue;
  }
  const examples = exampleFiles(patternDir);
  if (!examples.length) continue;
  const multi = examples.length > 1;

  for (const ex of examples) {
    const title = multi
      ? `Patterns/${fm.title}/${ex.exampleName}`
      : `Patterns/${fm.title}`;
    const importPath = `../../../../docs-website/src/app/pages/patterns/${id}/examples/${ex.stem}`;
    const summary = (fm.summary || '').replace(/\s+/g, ' ').trim();
    const src = `// GENERATED by tools/patterns/generate-storybook-stories.mjs — do not edit.
import type { Meta, StoryObj } from '@storybook/angular';

// Patterns stories reuse the docs-website pattern examples as the single source,
// so they reach across the project boundary on purpose.
// eslint-disable-next-line @nx/enforce-module-boundaries
import { ${ex.constName} } from '${importPath}';

const meta: Meta = {
  title: '${title.replace(/'/g, "\\'")}',
  component: ${ex.constName}.dynamicComponent,
  parameters: {
    docs: {
      description: {
        component:
          '${summary.replace(/'/g, "\\'")} See the full pattern guidance in the docs site.',
      },
    },
  },
};

export default meta;
type Story = StoryObj;

export const Overview: Story = {};
`;
    const fileKey = ex.stem.replace(/\.example$/, '');
    generated[`${fileKey}.stories.ts`] = src;
  }
}

const prettierOptions =
  (await prettier.resolveConfig(join(storiesDir, 'x.stories.ts'))) ?? {};
const formatted = {};
for (const [name, src] of Object.entries(generated)) {
  formatted[name] = await prettier.format(src, {
    ...prettierOptions,
    parser: 'typescript',
  });
}

if (errors.length) {
  console.error('✗ ' + errors.join('\n✗ '));
  process.exit(1);
}

const existing = existsSync(storiesDir)
  ? readdirSync(storiesDir).filter((f) => f.endsWith('.stories.ts'))
  : [];
const wanted = new Set(Object.keys(formatted));

if (isCheck) {
  let drift = false;
  for (const [name, src] of Object.entries(formatted)) {
    const file = join(storiesDir, name);
    if (!existsSync(file) || readFileSync(file, 'utf8') !== src) {
      console.error(`✗ stale or missing story: ${name}`);
      drift = true;
    }
  }
  for (const name of existing) {
    if (!wanted.has(name)) {
      console.error(`✗ orphan story (no matching example): ${name}`);
      drift = true;
    }
  }
  if (drift) {
    console.error('\nRun `npm run patterns:stories` and commit the result.');
    process.exit(1);
  }
  console.log(`✓ ${wanted.size} pattern story file(s) in sync.`);
} else {
  mkdirSync(storiesDir, { recursive: true });
  for (const name of existing) {
    if (!wanted.has(name)) rmSync(join(storiesDir, name));
  }
  for (const [name, src] of Object.entries(formatted)) {
    writeFileSync(join(storiesDir, name), src);
    console.log(`  wrote ${name}`);
  }
  console.log(`✓ generated ${wanted.size} pattern story file(s).`);
}
